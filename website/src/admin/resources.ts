/**
 * What the admin panel can manage. Each resource is one table with its columns described as form
 * fields; the generic ResourceManager turns this into a list, a create form and an edit form.
 */
import type { StaffRole, TableName } from "../lib/backend/types";
import type { Field, Option } from "./form";

export interface Column {
  /** Column name or dotted path. */
  key: string;
  label: string;
  kind?: "text" | "bool" | "date" | "image" | "badge" | "list";
}

export interface Resource {
  id: string;
  table: TableName;
  title: string;
  singular: string;
  description: string;
  group: "People" | "Learning" | "Product" | "Site";
  /** Lowest role that can open it. */
  minRole: StaffRole;
  columns: Column[];
  /** Column used for the row title in lists and confirmations. */
  titleKey: string;
  fields: Field[];
  orderBy: { column: string; ascending?: boolean }[];
  search: string[];
  /** Defaults for a new row. */
  defaults: Record<string, unknown>;
  /** Contributors only see and edit rows where this column equals their linked person. */
  ownRowOnly?: boolean;
  canCreate?: StaffRole;
  canDelete?: StaffRole;
  /** Preview the public page for a row. */
  publicPath?: (row: Record<string, unknown>) => string | null;
}

