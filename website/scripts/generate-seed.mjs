// Builds supabase/seed.sql from the content that ships in the repository (tutorials, releases,
// roadmap), so a new database starts identical to the static site. Run: node scripts/generate-seed.mjs
// Add --check to fail when the committed file is out of date.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const out = fileURLToPath(new URL("../../supabase/seed.sql", import.meta.url));
const load = (p) => import(new URL(`../src/${p}`, import.meta.url).href);
const { MODULES, EPISODES } = await load("tutorials.ts");
const { RELEASES } = await load("releases.ts");
const { MILESTONES, PLANNED_RELEASES, LIMITATIONS, OPEN_TASKS } = await load("roadmap.ts");

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replaceAll("'", "''")}'`);
const arr = (a = []) => (a.length ? `array[${a.map(q).join(", ")}]::text[]` : "'{}'::text[]");
const json = (v) => `$j$${JSON.stringify(v)}$j$::jsonb`;

const lines = [
  "-- Generated by website/scripts/generate-seed.mjs from the repository content. Safe to re-run:",
  "-- existing rows with the same key are updated, rows you added in the admin panel are left alone.",
  "",
];

lines.push("-- tutorial modules");
MODULES.forEach((m, i) =>
  lines.push(
    `insert into public.tutorial_modules (id, title, level, summary, outcome, sort) values (${[q(m.id), q(m.title), q(m.level), q(m.summary), q(m.outcome), (i + 1) * 10].join(", ")})
  on conflict (id) do update set title = excluded.title, level = excluded.level, summary = excluded.summary, outcome = excluded.outcome, sort = excluded.sort;`,
  ),
);

lines.push("", "-- tutorial episodes");
for (const e of EPISODES) {
  const content = {
    goals: e.goals,
    prerequisites: e.prerequisites,
    outline: e.outline,
    samples: e.samples,
    tutor: e.tutor,
    docs: e.docs,
  };
  lines.push(
    `insert into public.tutorials (slug, number, module, level, minutes, title, summary, content, status) values (${[q(e.slug), e.number, q(e.module), q(e.level), e.minutes, q(e.title), q(e.summary), json(content), q(e.status)].join(", ")})
  on conflict (slug) do nothing;`,
  );
}

lines.push("", "-- releases");
for (const r of RELEASES) {
  lines.push(
    `insert into public.releases (version, released_on, title, summary, features, fixes, upgrade, limits, npm_url, published) values (${[
      q(r.version),
      q(r.date),
      q(r.title),
      q(r.summary),
      json(r.features),
      arr(r.fixes),
      arr(r.upgrade),
      arr(r.limits),
      q(`https://www.npmjs.com/package/@nyxapi/core/v/${r.version}`),
      "true",
    ].join(", ")})
  on conflict (version) do nothing;`,
  );
}

lines.push("", "-- roadmap milestones");
for (const m of MILESTONES) {
  lines.push(
    `insert into public.roadmap_milestones (number, title, summary, items) values (${[m.id, q(m.title), q(m.summary), json(m.items)].join(", ")})
  on conflict (number) do nothing;`,
  );
}
lines.push("", "-- planned releases");
PLANNED_RELEASES.forEach((p, i) =>
  lines.push(
    `insert into public.planned_releases (version, theme, items, sort) values (${[q(p.version), q(p.theme), arr(p.items), (i + 1) * 10].join(", ")})
  on conflict (version) do nothing;`,
  ),
);
lines.push("", "-- known limitations");
LIMITATIONS.forEach((l, i) =>
  lines.push(
    `insert into public.limitations (title, detail, workaround, area, sort) select ${[q(l.title), q(l.detail), q(l.workaround), q(l.area), (i + 1) * 10].join(", ")}
  where not exists (select 1 from public.limitations where title = ${q(l.title)});`,
  ),
);
lines.push("", "-- open tasks");
OPEN_TASKS.forEach((t, i) =>
  lines.push(
    `insert into public.issues (title, detail, area, size, sort) select ${[q(t.title), q(t.detail), q(t.area), q(t.size), (i + 1) * 10].join(", ")}
  where not exists (select 1 from public.issues where title = ${q(t.title)});`,
  ),
);

lines.push(
  "",
  "-- site settings",
  `insert into public.site_settings (key, value) values ('community.intro', '"NyxAPI is built by people who report bugs, write docs, ship code and teach. This page is for them."'::jsonb) on conflict (key) do nothing;`,
  `insert into public.site_settings (key, value) values ('tutors.intro', '"Tutors record the video lessons in the NyxAPI playlist. Pick an episode and help the project grow."'::jsonb) on conflict (key) do nothing;`,
  "",
);

const text = lines.join("\n");
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(out, "utf8");
  } catch {
    /* missing */
  }
  if (current !== text) {
    console.error("supabase/seed.sql is out of date. Run: node website/scripts/generate-seed.mjs");
    process.exit(1);
  }
  console.log("seed.sql is up to date");
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out} (${text.split("\n").length} lines)`);
}
void root;
