import type { Metadata } from "next";
import Link from "next/link";
import { NpmStatus } from "@/components/NpmStatus";
import { RELEASES } from "@/releases";

export const metadata: Metadata = {
  title: "Releases",
  description:
    "Every NyxAPI version, what it added, what it fixed and what it still does not do, with live npm publish status.",
};

/** Renders `code` spans in release text. */
function Inline({ text }: { text: string }) {
  return (
    <>{text.split("`").map((part, i) => (i % 2 === 1 ? <code key={i}>{part}</code> : part))}</>
  );
}

export default function Page() {
  return (
    <div className="wrap" style={{ padding: "36px 0 80px", maxWidth: 900 }}>
      <h1 style={{ fontSize: "clamp(2rem,4vw,2.7rem)" }}>Releases</h1>
      <p style={{ color: "var(--muted)", fontSize: "1.15rem" }}>
        Every version, what it brought, and what it still does not do. All packages share one
        version number. The badge on each version comes from the npm registry when you open this
        page, so it only says &quot;on npm&quot; for versions that really are published.
      </p>
      <p>
        Full per-package notes live in each package&apos;s <code>CHANGELOG.md</code>, generated by
        Changesets. To install a specific version:{" "}
        <code>npm install @nyxapi/core@{RELEASES[0]?.version}</code>. See{" "}
        <Link href="/install/">Install</Link>.
      </p>

      <nav aria-label="Versions" className="pill-row" style={{ margin: "18px 0 8px" }}>
        {RELEASES.map((r) => (
          <a className="pill" key={r.version} href={`#v${r.version}`}>
            <b>v{r.version}</b>
          </a>
        ))}
      </nav>

      {RELEASES.map((r, i) => (
        <section className="release" key={r.version} id={`v${r.version}`}>
          <header className="release-head">
            <h2>
              v{r.version}
              {i === 0 && <span className="badge live">newest</span>}
            </h2>
            <NpmStatus version={r.version} />
            <span className="release-date">{r.date ?? "initial release"}</span>
          </header>
          <h3 className="release-title">
            <Inline text={r.title} />
          </h3>
          <p>
            <Inline text={r.summary} />
          </p>

          <h4>What it added</h4>
          <ul className="release-list">
            {r.features.map((f) => (
              <li key={f.label}>
                <b>
                  <Inline text={f.label} />.
                </b>{" "}
                <Inline text={f.detail} />
              </li>
            ))}
          </ul>

          {r.fixes && (
            <>
              <h4>Fixes and hardening</h4>
              <ul className="release-list">
                {r.fixes.map((f) => (
                  <li key={f}>
                    <Inline text={f} />
                  </li>
                ))}
              </ul>
            </>
          )}
          {r.upgrade && (
            <>
              <h4>Upgrading</h4>
              <ul className="release-list">
                {r.upgrade.map((f) => (
                  <li key={f}>
                    <Inline text={f} />
                  </li>
                ))}
              </ul>
            </>
          )}
          {r.limits && (
            <>
              <h4>Not in this version</h4>
              <ul className="release-list">
                {r.limits.map((f) => (
                  <li key={f}>
                    <Inline text={f} />
                  </li>
                ))}
              </ul>
            </>
          )}
        </section>
      ))}
    </div>
  );
}
