import type { ResolvedConfig } from "./config.js";
import type { ApiModel, Diagnostic, OperationModel, PropertyNode, TypeNode } from "./ir.js";
import { propertyKey, typeName, variableName } from "./naming.js";
import type { TreeNode } from "./tree.js";

export interface GeneratedFile {
  /** Relative to the output directory, always `/`-separated. */
  path: string;
  content: string;
}

const METHOD_ORDER = ["get", "head", "post", "put", "patch", "delete"] as const;
const pad = (n: number): string => "  ".repeat(n);

const comment = (text: string): string => text.replace(/\*\//g, "*\\/");

function docBlock(lines: (string | undefined)[], level: number): string {
  const body = lines
    .filter((l): l is string => !!l)
    .flatMap((l) => comment(l).split(/\r?\n/))
    .map((l) => l.trimEnd());
  if (body.length === 0) return "";
  if (body.length === 1) return `${pad(level)}/** ${body[0] as string} */\n`;
  return `${pad(level)}/**\n${body.map((l) => `${pad(level)} * ${l}`.trimEnd()).join("\n")}\n${pad(level)} */\n`;
}

function wrap(node: TypeNode, level: number): string {
  const text = fmt(node, level);
  return node.kind === "union" || node.kind === "intersection" ? `(${text})` : text;
}

function fmt(node: TypeNode, level: number): string {
  switch (node.kind) {
    case "ref":
      return node.name;
    case "primitive":
      return node.type;
    case "literal":
      return JSON.stringify(node.value);
    case "array":
      return `${wrap(node.item, level)}[]`;
    case "union":
      return node.members.map((m) => fmt(m, level)).join(" | ");
    case "intersection":
      return node.members.map((m) => wrap(m, level)).join(" & ");
    case "object": {
      if (node.properties.length === 0)
        return node.additional
          ? `Record<string, ${fmt(node.additional, level)}>`
          : "Record<string, never>";
      const props = node.properties.map((p) => property(p, level + 1)).join("");
      const base = `{\n${props}${pad(level)}}`;
      return node.additional ? `${base} & Record<string, ${fmt(node.additional, level)}>` : base;
    }
  }
}

function property(p: PropertyNode, level: number): string {
  const doc = docBlock([p.description, p.deprecated ? "@deprecated" : undefined], level);
  return `${doc}${pad(level)}${propertyKey(p.name)}${p.required ? "" : "?"}: ${fmt(p.type, level)};\n`;
}

function typeDecl(name: string, node: TypeNode, description?: string): string {
  const doc = docBlock([description], 0);
  if (node.kind === "object" && node.properties.length > 0 && !node.additional)
    return `${doc}export interface ${name} ${fmt(node, 0)}\n`;
  return `${doc}export type ${name} = ${fmt(node, 0)};\n`;
}

/** `ErrorCase<401, X> | ErrorCase<404, Y>`; ranges and `default` become `number`; no docs → `unknown`. */
function errorUnion(op: OperationModel): string {
  if (op.errors.length === 0) return "unknown";
  const byStatus = new Map<string, TypeNode[]>();
  for (const e of op.errors) byStatus.set(e.status, [...(byStatus.get(e.status) ?? []), e.type]);
  return [...byStatus.keys()]
    .sort()
    .map((status) => {
      const types = byStatus.get(status) as TypeNode[];
      const body =
        types.length === 1
          ? fmt(types[0] as TypeNode, 0)
          : fmt({ kind: "union", members: types }, 0);
      return `ErrorCase<${/^\d{3}$/.test(status) ? status : "number"}, ${body}>`;
    })
    .join(" | ");
}

interface OperationTypes {
  prefix: string;
  body?: string;
  data: string;
  error: string;
  request?: string;
}

const operationTypes = (op: OperationModel): OperationTypes => {
  const prefix = typeName(op.id);
  const t: OperationTypes = { prefix, data: `${prefix}Data`, error: `${prefix}ErrorBody` };
  if (op.body) t.body = `${prefix}Body`;
  if (op.queryParams.length > 0 || op.headerParams.length > 0) t.request = `${prefix}Request`;
  return t;
};

function requestInterface(name: string, op: OperationModel): string {
  const section = (key: string, params: OperationModel["queryParams"]): string => {
    if (params.length === 0) return "";
    const allOptional = params.every((p) => !p.required);
    const inner = params
      .map(
        (p) =>
          `${docBlock([p.description], 2)}${pad(2)}${propertyKey(p.name)}${p.required ? "" : "?"}: ${fmt(p.type, 2)};\n`,
      )
      .join("");
    return `${pad(1)}${key}${allOptional ? "?" : ""}: {\n${inner}${pad(1)}};\n`;
  };
  const doc = docBlock([`Request options for \`${op.method.toUpperCase()} ${op.path}\`.`], 0);
  return `${doc}export interface ${name} {\n${section("query", op.queryParams)}${section("headers", op.headerParams)}}\n`;
}

const HEADER = (model: ApiModel): string =>
  `// <auto-generated by @nyxapi/codegen. Do not edit: changes are overwritten.>\n// Source: ${comment(model.title)} ${comment(model.version)}\n/* eslint-disable */\n\n`;

/** Emit `types.ts`, `client.ts` and `index.ts`. Pure and deterministic: same model, same bytes. */
/** Runtime `Shape` literal (see `@nyxapi/core`) for a type; `void`/`undefined` accept anything. */
/** `"__proto__": x` in an object literal sets the prototype instead of defining a property. */
const literalKey = (name: string): string =>
  name === "__proto__" ? '["__proto__"]' : JSON.stringify(name);

function shapeOf(node: TypeNode, level: number): string {
  const p = (n: number): string => "  ".repeat(n);
  switch (node.kind) {
    case "ref":
      return `{ k: "ref", name: ${JSON.stringify(node.name)} }`;
    case "literal":
      return `{ k: "lit", v: ${JSON.stringify(node.value)} }`;
    case "primitive":
      switch (node.type) {
        case "string":
        case "number":
        case "boolean":
        case "null":
          return `{ k: ${JSON.stringify(node.type)} }`;
        case "Blob":
          return '{ k: "blob" }';
        default:
          return '{ k: "any" }';
      }
    case "array":
      return `{ k: "arr", of: ${shapeOf(node.item, level)} }`;
    case "union":
    case "intersection":
      return `{ k: ${node.kind === "union" ? '"or"' : '"and"'}, of: [${node.members.map((m) => shapeOf(m, level)).join(", ")}] }`;
    case "object": {
      const props = node.properties
        .map(
          (prop) =>
            `${p(level + 2)}${literalKey(prop.name)}: { shape: ${shapeOf(prop.type, level + 2)}, required: ${String(prop.required)} },\n`,
        )
        .join("");
      const body = props ? `{\n${props}${p(level + 1)}}` : "{}";
      return `{\n${p(level + 1)}k: "obj",\n${p(level + 1)}props: ${body},\n${p(level + 1)}extra: ${node.additional ? shapeOf(node.additional, level + 1) : "null"},\n${p(level)}}`;
    }
  }
}

export function emit(
  model: ApiModel,
  root: TreeNode,
  cfg: ResolvedConfig,
  diagnostics: Diagnostic[],
): GeneratedFile[] {
  // every exported type name must be unique
  const registry = new Map<string, string>();
  const claim = (name: string, what: string): void => {
    const other = registry.get(name);
    if (other !== undefined)
      diagnostics.push({
        level: "error",
        code: "NAME_COLLISION",
        message: `Generated type "${name}" is produced by both ${other} and ${what}`,
      });
    registry.set(name, what);
  };
  let usesErrorCase = false;
  const shapeImports = new Set<string>();
  const shapeDecls: string[] = [];
  let types = "";
  for (const s of model.schemas) {
    claim(s.name, `schema "${s.sourceName}"`);
    types += typeDecl(s.name, s.type, s.description) + "\n";
  }
  const ops = [...model.operations].sort((a, b) => a.id.localeCompare(b.id));
  for (const op of ops) {
    const t = operationTypes(op);
    const doc = `\`${op.method.toUpperCase()} ${op.path}\``;
    if (op.body && t.body) {
      claim(t.body, `${op.id} body`);
      types += `${docBlock([`Request body of ${doc}.`], 0)}export type ${t.body} = ${fmt(op.body.type, 0)}${op.body.required ? "" : " | undefined"};\n\n`;
    }
    claim(t.data, `${op.id} data`);
    types += `${docBlock([`Success payload of ${doc}.`], 0)}export type ${t.data} = ${fmt(op.success, 0)};\n\n`;
    claim(t.error, `${op.id} error`);
    types += `${docBlock([`Documented error responses of ${doc}. Narrow on \`error.status\`.`], 0)}export type ${t.error} = ${errorUnion(op)};\n\n`;
    if (op.errors.length > 0) usesErrorCase = true;
    if (t.request) {
      claim(t.request, `${op.id} request`);
      types += requestInterface(t.request, op) + "\n";
    }
  }

  types =
    HEADER(model) +
    (usesErrorCase ? 'import type { ErrorCase } from "@nyxapi/core";\n\n' : "") +
    types;

  // ---- client ------------------------------------------------------------------------------
  let usesNoRequest = false;
  const usedTypes = new Set<string>();
  const body = emitNode(root, 2, []);
  function emitNode(node: TreeNode, level: number, vars: string[]): string {
    let out = "";
    for (const method of METHOD_ORDER) {
      const op = node.methods.get(method);
      if (!op) continue;
      const t = operationTypes(op);
      const request = t.request ?? "NoRequest";
      if (t.request) usedTypes.add(t.request);
      else usesNoRequest = true;
      usedTypes.add(t.data).add(t.error);
      const isQuery = method === "get" || method === "head";
      const bodyType = t.body ?? "void";
      if (t.body) usedTypes.add(t.body);
      const generics = isQuery
        ? `${request}, ${t.data}, ${t.error}`
        : `${request}, ${bodyType}, ${t.data}, ${t.error}`;
      const params = op.pathParams.length
        ? `, params: { ${op.pathParams.map((p) => `${propertyKey(p.name)}: ${variableFor(vars, op, p.name)}`).join(", ")} }`
        : "";
      const styled = op.queryParams.filter((p) => p.style);
      const queryStyles = styled.length
        ? `, queryStyles: { ${styled.map((p) => `${propertyKey(p.name)}: ${JSON.stringify(p.style)}`).join(", ")} }`
        : "";
      let validate = "";
      if (cfg.validation && op.responseKind === "json") {
        validate = `, validate: { shape: ${t.prefix}Response, shapes }`;
        shapeImports.add(`${t.prefix}Response`);
        shapeDecls.push(
          `/** Response shape of \`${op.method.toUpperCase()} ${op.path}\`. */\nexport const ${t.prefix}Response: Shape = ${shapeOf(op.success, 0)};\n`,
        );
      }
      const flags = `${queryStyles}${validate}${op.body ? ", hasBody: true" : ""}${op.body && op.body.kind !== "json" ? `, bodyKind: ${JSON.stringify(op.body.kind)}` : ""}${op.responseKind === "json" ? "" : `, response: ${JSON.stringify(op.responseKind)}`}`;
      out += docBlock(
        [
          op.summary,
          op.description,
          `\`${op.method.toUpperCase()} ${op.path}\``,
          op.deprecated ? "@deprecated" : undefined,
        ],
        level,
      );
      out += `${pad(level)}${method}: client.${isQuery ? "query" : "mutation"}<${generics}>({ operationId: ${JSON.stringify(op.id)}, method: ${JSON.stringify(method)}, path: ${JSON.stringify(op.path)}${params}${flags} }),\n`;
    }
    for (const key of [...node.children.keys()].sort()) {
      const child = node.children.get(key) as TreeNode;
      if (child.param) {
        const name = uniqueVar(vars, child.param.name);
        const pt = fmt(child.param.type, 0);
        const paramType =
          child.param.type.kind === "primitive" && child.param.type.type === "unknown"
            ? "string"
            : pt;
        if (child.param.type.kind === "ref") usedTypes.add(child.param.type.name);
        out += `${pad(level)}${propertyKey(key)}: (${name}: ${paramType}) => ({\n${emitNode(child, level + 1, [...vars, `${child.param.name}=${name}`])}${pad(level)}}),\n`;
      } else
        out += `${pad(level)}${propertyKey(key)}: {\n${emitNode(child, level + 1, vars)}${pad(level)}},\n`;
    }
    return out;
  }
  const core = ["NyxClient", ...(usesNoRequest ? ["NoRequest"] : [])].join(", ");
  const typeImports = [...usedTypes].sort();
  let client = HEADER(model);
  client += `import type { ${core} } from "@nyxapi/core";\n`;
  if (shapeImports.size > 0)
    client += `import { shapes, ${[...shapeImports].sort().join(", ")} } from "./shapes.js";\n`;
  if (typeImports.length > 0)
    client += `import type {\n${typeImports.map((n) => `${pad(1)}${n},\n`).join("")}} from "./types.js";\n`;
  client += `\n/**\n * Create the typed client tree. Create one \`NyxClient\` per user/request on the server.\n */\nexport function createApi(client: NyxClient) {\n  return {\n${body}  };\n}\n\nexport type Api = ReturnType<typeof createApi>;\n`;

  const index = `${HEADER(model)}export * from "./types.js";\nexport { createApi, type Api } from "./client.js";\n`;
  const files: GeneratedFile[] = [
    { path: "types.ts", content: types.trimEnd() + "\n" },
    { path: "client.ts", content: client },
    { path: "index.ts", content: index },
  ];
  if (cfg.validation) {
    const table = model.schemas
      .map((sc) => `  ${JSON.stringify(sc.name)}: ${shapeOf(sc.type, 1)},\n`)
      .join("");
    files.push({
      path: "shapes.ts",
      content:
        HEADER(model) +
        `import type { Shape } from "@nyxapi/core";\n\n/** Named schemas, referenced by \`{ k: "ref" }\`. */\nexport const shapes: Readonly<Record<string, Shape>> = {\n${table}};\n\n${shapeDecls.join("\n")}`.trimEnd() +
        "\n",
    });
  }
  return files;
}

/** Variables are tracked as "wireName=variable" strings along the path. */
function variableFor(vars: string[], op: OperationModel, name: string): string {
  void op;
  for (let i = vars.length - 1; i >= 0; i--) {
    const entry = vars[i] as string;
    const eq = entry.indexOf("=");
    if (entry.slice(0, eq) === name) return entry.slice(eq + 1);
  }
  return variableName(name);
}

function uniqueVar(vars: string[], wireName: string): string {
  const taken = new Set(vars.map((v) => v.slice(v.indexOf("=") + 1)));
  const base = variableName(wireName);
  let name = base;
  for (let i = 2; taken.has(name); i++) name = `${base}${String(i)}`;
  return name;
}
